#!/usr/bin/env node
// Collects verification evidence for a phase into docs/proof/phase-<N>/:
//   test-report.txt   full `node --test` output
//   scenarios/<case>/out.jsonl   headless output of each tests/scenarios/<case>
//   summary.md        pass/fail table, determinism check (two runs, sha256), machine info, git commit
// Usage: node scripts/evidence.mjs <phase-number>
// Exit code is non-zero if any test or determinism check fails.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, totalmem } from 'node:os';
import { join } from 'node:path';

const phase = process.argv[2];
if (!/^[1-4]$/.test(phase ?? '')) {
  console.error('usage: node scripts/evidence.mjs <1-4>');
  process.exit(1);
}
const outDir = join('docs', 'proof', `phase-${phase}`);
mkdirSync(join(outDir, 'scenarios'), { recursive: true });
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const node = process.execPath;
let ok = true;

// 1. unit + contract tests
const t = spawnSync(node, ['--test', 'tests/'], { encoding: 'utf8' });
writeFileSync(join(outDir, 'test-report.txt'), t.stdout + t.stderr);
const count = (k) => (t.stdout.match(new RegExp(`ℹ ${k} (\\d+)`)) ?? [])[1] ?? '?';
if (t.status !== 0) ok = false;

// 2. headless scenarios, each run twice for determinism
const rows = [];
for (const name of readdirSync(join('tests', 'scenarios')).sort()) {
  const dir = join('tests', 'scenarios', name);
  const c = JSON.parse(readFileSync(join(dir, 'case.json'), 'utf8'));
  const args = ['src/headless/cli.js', '--seed', String(c.seed), '--night', '1', '--ticks', String(c.ticks), '--snapshot-every', String(c.snapshot_every ?? 10)];
  if (existsSync(join(dir, 'scenario.json'))) args.push('--scenario', join(dir, 'scenario.json'));
  if (existsSync(join(dir, 'inputs.json'))) args.push('--inputs', join(dir, 'inputs.json'));
  const caseOut = join(outDir, 'scenarios', name);
  mkdirSync(caseOut, { recursive: true });
  const outs = [];
  let status = 0;
  for (const run of [1, 2]) {
    const f = join(caseOut, run === 1 ? 'out.jsonl' : 'out.run2.jsonl');
    const r = spawnSync(node, [...args, '--out', f], { encoding: 'utf8' });
    status ||= r.status;
    outs.push(existsSync(f) ? readFileSync(f, 'utf8') : '');
  }
  const same = outs[0] === outs[1] && outs[0] !== '';
  if (status !== 0 || !same) ok = false;
  const end = outs[0].trim().split('\n').at(-1) ?? '';
  writeFileSync(join(caseOut, 'command.txt'), `node ${args.join(' ')} --out out.jsonl\n`);
  rows.push(`| ${name} | ${c.description} | exit ${status} | ${same ? 'identical' : 'DIFFERENT'} (${sha(outs[0])}) | \`${end}\` |`);
}

const commit = spawnSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).stdout.trim() || '(no commit)';
const dirty = spawnSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).stdout.trim() ? ' (uncommitted changes present)' : '';
writeFileSync(
  join(outDir, 'summary.md'),
  `# Phase ${phase} evidence (generated by scripts/evidence.mjs)

- Generated: ${new Date().toISOString()}
- Commit: ${commit}${dirty}
- Machine: ${platform()} ${release()}, ${cpus()[0]?.model ?? '?'} x${cpus().length}, ${(totalmem() / 2 ** 30).toFixed(1)} GB RAM, Node ${process.version}

## Tests (\`npm test\`)

pass ${count('pass')} · fail ${count('fail')} · exit ${t.status} — full output in [test-report.txt](test-report.txt)

## Headless scenarios (each run twice, outputs compared byte for byte)

| Case | What it checks | Exit | Determinism (sha256) | End line |
|---|---|---|---|---|
${rows.join('\n')}

Overall: **${ok ? 'PASS' : 'FAIL'}**
`,
);
console.log(`${ok ? 'PASS' : 'FAIL'}: evidence written to ${outDir}`);
process.exit(ok ? 0 : 1);
